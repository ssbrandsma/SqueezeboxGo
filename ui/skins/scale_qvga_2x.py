#!/usr/bin/env python3
"""scale_qvga_2x.py — bootstrap the 640x480 RG35XX H skin from the QVGA Radio skin.

Reads the pinned squeezeplay tree (NOT vendored into git) and writes:
  RG35XXHBaseSkin/      <- QVGAbaseSkin      (lua transformed, images 2x)
  RG35XXHLandscapeSkin/ <- QVGAlandscapeSkin (lua transformed, images 2x)

Lua transform (see ui/skins/README.md for the audited rules):
  * rename applet identifiers QVGAbaseSkin/QVGAlandscapeSkin (+ string keys)
  * double every decimal pixel/geometry literal, EXCEPT an audited exclusion
    set: hex colors, style identifiers, hidden/horizontal/zOrder/frameRate
    flags, NOWPLAYING_TRACKINFO_LINES, setVideoMode bpp, * / operands
    (counts and half-screen divisors), Meta files (rename only), comments
    (explicit prose replacements only) and strings (except artworkSize WxH).
  * default video mode 320x240 -> 640x480 (falls out of the doubling).

Image transform: 2x nearest-neighbor PNG scale, stdlib only (struct+zlib).
Supports 8/16-bit non-interlaced color types 0/2/3/4/6; anything else
aborts with an error so new upstream assets cannot slip through silently.

Deterministic: sorted traversal, fixed zlib level, no timestamps.

Usage:
  scale_qvga_2x.py --src /path/to/squeezeplay@758bc11 --out ui/skins
  scale_qvga_2x.py --src ... --out ui/skins --check   # verify committed files
"""
import argparse
import os
import re
import struct
import sys
import zlib

SCALE = 2
APPLETS_SUBDIR = os.path.join("src", "squeezeplay", "share", "applets")

SKINS = (
    ("QVGAbaseSkin", "RG35XXHBaseSkin"),
    ("QVGAlandscapeSkin", "RG35XXHLandscapeSkin"),
)

# identifier / prose renames applied to lua + strings.txt
IDENT_RENAMES = (
    ("QVGAlandscapeSkin", "RG35XXHLandscapeSkin"),
    ("QVGAbaseSkin", "RG35XXHBaseSkin"),
    ("QVGALANDSCAPE_SKIN", "RG35XXHLANDSCAPE_SKIN"),
)
PROSE_RENAMES = (
    ("The skin base for any 320x240 or 240x320 screen",
     "The skin base for the RG35XX H 640x480 display (2x QVGA bootstrap)"),
    ("This applet implements the base skin for Qvga screens",
     "This applet implements the base skin for the RG35XX H 640x480 display"),
    ("base class for 240 x 320 and 320 x 240 resolutions",
     "base class for the 640x480 RG35XX H display"),
    ("The skin for the Squeezebox Controller",
     "The 640x480 skin for the RG35XX H (2x QVGA bootstrap)"),
    ("This applet implements the skin for the Squeezebox Controller",
     "This applet implements the 640x480 skin for the RG35XX H"),
    ("QVGA Landscape Skin", "RG35XX H 640x480 Skin"),
    ("320x240", "640x480"),
)

GENERATED_HEADER = (
    "-- GENERATED by ui/skins/scale_qvga_2x.py from {src_applet} @ {pin}.\n"
    "-- 2x integer bootstrap for the 640x480 RG35XX H display. Do not edit;\n"
    "-- re-run the script against the pinned tree instead.\n\n"
)

# assignment keys whose numeric values are NOT pixels and must be kept
EXCLUDE_KEYS = frozenset({
    "hidden", "horizontal", "zOrder", "frameRate",
    "NOWPLAYING_TRACKINFO_LINES",
})


# ---------------------------------------------------------------- lua lexer
class Tok:
    __slots__ = ("kind", "text")

    def __init__(self, kind, text):
        self.kind = kind  # code | comment | string | number | other
        self.text = text


def lex_lua(src):
    """Split lua source into a flat token list (comments/strings/numbers safe)."""
    toks = []
    i, n = 0, len(src)
    buf = []
    def flush(kind="code"):
        if buf:
            toks.append(Tok(kind, "".join(buf)))
            del buf[:]
    while i < n:
        c = src[i]
        # line/block comment
        if c == "-" and i + 1 < n and src[i + 1] == "-":
            flush()
            m = re.match(r"--\[(=*)\[", src[i:])
            if m:
                eq = m.group(1)
                end = "--]" + eq + "]"
                j = src.find(end, i + len(m.group(0)))
                j = n if j < 0 else j + len(end)
                toks.append(Tok("comment", src[i:j]))
                i = j
            else:
                j = src.find("\n", i)
                j = n if j < 0 else j
                toks.append(Tok("comment", src[i:j]))
                i = j
            continue
        # strings
        if c in "\"'":
            flush()
            j = i + 1
            while j < n and src[j] != c:
                if src[j] == "\\":
                    j += 1
                j += 1
            j = min(j + 1, n)
            toks.append(Tok("string", src[i:j]))
            i = j
            continue
        if c == "[":
            m = re.match(r"\[(=*)\[", src[i:])
            if m:
                flush()
                eq = m.group(1)
                end = "]" + eq + "]"
                j = src.find(end, i + len(m.group(0)))
                j = n if j < 0 else j + len(end)
                toks.append(Tok("string", src[i:j]))
                i = j
                continue
        # hex number
        if c == "0" and i + 1 < n and src[i + 1] in "xX":
            flush()
            m = re.match(r"0[xX][0-9a-fA-F]+", src[i:])
            toks.append(Tok("number", m.group(0)))
            i += len(m.group(0))
            continue
        # decimal number (not part of identifier: prev char check)
        if c.isdigit() and not (buf and (buf[-1].isalnum() or buf[-1] == "_")):
            # also not identifier char right before across flush boundary:
            # 'buf' holds current code run; identifier chars never flushed
            # mid-name because we only flush on comment/string/number bounds.
            flush()
            m = re.match(r"\d+(?:\.\d+)?", src[i:])
            toks.append(Tok("number", m.group(0)))
            i += len(m.group(0))
            continue
        # identifier char continues code run (digits inside names stay code)
        buf.append(c)
        i += 1
    flush()
    return toks


def scale_applet_lua(text, src_applet, pin):
    toks = lex_lua(text)
    out = []
    for idx, t in enumerate(toks):
        if t.kind == "comment":
            s = t.text
            for old, new in IDENT_RENAMES + PROSE_RENAMES:
                s = s.replace(old, new)
            out.append(s)
        elif t.kind == "string":
            s = t.text
            for old, new in IDENT_RENAMES:
                s = s.replace(old, new)
            out.append(s)
        elif t.kind == "number":
            if t.text.startswith(("0x", "0X")):
                out.append(t.text)  # color / bitmask: never scale
                continue
            if "." in t.text:
                raise SystemExit("unexpected float literal in skin: " + t.text)
            if _excluded_number(toks, idx):
                out.append(t.text)
            else:
                out.append(str(int(t.text) * SCALE))
        else:  # code
            s = t.text
            for old, new in IDENT_RENAMES:
                s = s.replace(old, new)
            out.append(s)
    text = "".join(out)
    # artwork request sizes live in strings: scale WxH on artworkSize lines
    def _art(m):
        return "artworkSize = '%dx%d'" % (int(m.group(1)) * SCALE,
                                         int(m.group(2)) * SCALE)
    text = re.sub(r"artworkSize = '(\d+)x(\d+)'", _art, text)
    return GENERATED_HEADER.format(src_applet=src_applet, pin=pin) + text


def _excluded_number(toks, idx):
    """True if number token at idx is a non-pixel literal (audited rules)."""
    # rule 1: * / operand (counts, half-screen divisors): prev non-space char
    prev = []
    for j in range(idx - 1, -1, -1):
        if toks[j].kind != "code":
            break
        prev.append(toks[j].text)
        if toks[j].text.strip():
            break
    tail = "".join(reversed(prev)).rstrip()
    if tail.endswith(("*", "/")):
        return True
    # rule 2: assignment to an excluded key on this logical line
    line_start = tail.rfind("\n") + 1
    line_frag = tail[line_start:]
    m = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*[^=]*$", line_frag)
    if m and m.group(1) in EXCLUDE_KEYS:
        return True
    # rule 3: setVideoMode line (bpp arg)
    if "setVideoMode" in line_frag:
        return True
    return False


def scale_meta_lua(text, src_applet, pin):
    for old, new in IDENT_RENAMES + PROSE_RENAMES:
        text = text.replace(old, new)
    return GENERATED_HEADER.format(src_applet=src_applet, pin=pin) + text


def scale_strings(text):
    for old, new in IDENT_RENAMES + PROSE_RENAMES:
        text = text.replace(old, new)
    return text


# ---------------------------------------------------------------- png 2x
_PNG_SIG = struct.pack("8B", 137, 80, 78, 71, 13, 10, 26, 10)


def _chunks(data):
    if data[:8] != _PNG_SIG:
        raise ValueError("not a PNG")
    pos, out = 8, []
    while pos < len(data):
        (ln,) = struct.unpack(">I", data[pos:pos + 4])
        typ = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + ln]
        crc = data[pos + 8 + ln:pos + 12 + ln]
        out.append((typ, body, crc))
        pos += 12 + ln
    return out


def _mkchunk(typ, body):
    return struct.pack(">I", len(body)) + typ + body + struct.pack(
        ">I", zlib.crc32(typ + body) & 0xFFFFFFFF)


def png_2x(data, name="<png>"):
    chunks = _chunks(data)
    ihdr = next(b for t, b, _ in chunks if t == b"IHDR")
    w, h, bitd, ctype, comp, filt, inter = struct.unpack(">IIBBBBB", ihdr)
    if bitd not in (8, 16) or inter != 0 or ctype not in (0, 2, 3, 4, 6):
        raise ValueError("%s: unsupported PNG (bitdepth=%d colortype=%d "
                         "interlace=%d)" % (name, bitd, ctype, inter))
    if bitd == 16 and ctype == 3:
        raise ValueError("%s: invalid 16-bit palette PNG" % name)
    bpp = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype] * (bitd // 8)
    raw = zlib.decompress(b"".join(b for t, b, _ in chunks if t == b"IDAT"))
    stride = w * bpp
    # undo filters
    rows = []
    prev = bytearray(stride)
    pos = 0
    for _ in range(h):
        f = raw[pos]
        pos += 1
        cur = bytearray(raw[pos:pos + stride])
        pos += stride
        if f == 1:  # Sub
            for k in range(bpp, stride):
                cur[k] = (cur[k] + cur[k - bpp]) & 0xFF
        elif f == 2:  # Up
            for k in range(stride):
                cur[k] = (cur[k] + prev[k]) & 0xFF
        elif f == 3:  # Average
            for k in range(stride):
                a = cur[k - bpp] if k >= bpp else 0
                cur[k] = (cur[k] + ((a + prev[k]) >> 1)) & 0xFF
        elif f == 4:  # Paeth
            for k in range(stride):
                a = cur[k - bpp] if k >= bpp else 0
                b = prev[k]
                c = prev[k - bpp] if k >= bpp else 0
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                cur[k] = (cur[k] + pr) & 0xFF
        elif f != 0:
            raise ValueError("%s: bad filter %d" % (name, f))
        rows.append(bytes(cur))
        prev = cur
    # 2x nearest: replicate pixels horizontally and vertically (filter 0)
    out = bytearray()
    for row in rows:
        big = bytearray(2 * stride)
        for x in range(w):
            px = row[x * bpp:(x + 1) * bpp]
            big[2 * x * bpp:2 * x * bpp + bpp] = px
            big[(2 * x + 1) * bpp:(2 * x + 2) * bpp] = px
        out.append(0)
        out += big
        out.append(0)
        out += big
    idat = zlib.compress(bytes(out), 9)
    res = bytearray(_PNG_SIG)
    for typ, body, _ in chunks:
        if typ == b"IHDR":
            res += _mkchunk(typ, struct.pack(">IIBBBBB", 2 * w, 2 * h,
                                            bitd, ctype, comp, filt, inter))
        elif typ == b"IDAT":
            continue
        else:
            res += _mkchunk(typ, body)
        if typ == b"IHDR":
            for k in range(0, len(idat), 8192):
                res += _mkchunk(b"IDAT", idat[k:k + 8192])
    return bytes(res)


# ---------------------------------------------------------------- driver
def iter_files(top):
    for root, _dirs, files in os.walk(top):
        for f in sorted(files):
            yield os.path.join(root, f)


def generate(src_tree, out_dir, pin, do_lua=True, do_img=True):
    stats = {"lua": 0, "img": 0, "bytes_in": 0, "bytes_out": 0}
    for src_applet, dst_applet in SKINS:
        sdir = os.path.join(src_tree, APPLETS_SUBDIR, src_applet)
        ddir = os.path.join(out_dir, dst_applet)
        if not os.path.isdir(sdir):
            raise SystemExit("missing applet dir: " + sdir)
        for spath in iter_files(sdir):
            rel = os.path.relpath(spath, sdir)
            if rel.endswith(".pl"):
                continue  # dev-only helper scripts
            dpath = os.path.join(ddir, rel)
            base = os.path.basename(rel)
            is_lua = base.endswith(".lua")
            is_meta = is_lua and base.endswith("Meta.lua")
            is_img = rel.startswith("images" + os.sep)
            if is_lua and not do_lua:
                continue
            if is_img and not do_img:
                continue
            with open(spath, "rb") as fh:
                data = fh.read()
            stats["bytes_in"] += len(data)
            if is_lua:
                text = data.decode("utf-8")
                if is_meta:
                    text = scale_meta_lua(text, src_applet, pin)
                else:
                    text = scale_applet_lua(text, src_applet, pin)
                # rename the file itself to the new applet name
                for old, new in IDENT_RENAMES:
                    dpath = dpath.replace(old, new)
                out = text.encode("utf-8")
                stats["lua"] += 1
            elif base == "strings.txt":
                out = scale_strings(data.decode("utf-8")).encode("utf-8")
            elif is_img and base.endswith(".png"):
                out = png_2x(data, rel)
                stats["img"] += 1
            else:
                raise SystemExit("unexpected file in skin: " + rel)
            stats["bytes_out"] += len(out)
            os.makedirs(os.path.dirname(dpath) or ".", exist_ok=True)
            with open(dpath, "wb") as fh:
                fh.write(out)
    return stats


def main(argv=None):
    ap = argparse.ArgumentParser(description="2x bootstrap RG35XX H skin")
    ap.add_argument("--src", required=True, help="pinned squeezeplay tree")
    ap.add_argument("--out", required=True, help="output dir (ui/skins)")
    ap.add_argument("--pin", default="758bc11",
                    help="upstream pin label for provenance header")
    ap.add_argument("--lua-only", action="store_true")
    ap.add_argument("--img-only", action="store_true")
    args = ap.parse_args(argv)
    stats = generate(args.src, args.out, args.pin,
                     do_lua=not args.img_only, do_img=not args.lua_only)
    print("lua=%d img=%d bytes_in=%d bytes_out=%d" % (
        stats["lua"], stats["img"], stats["bytes_in"], stats["bytes_out"]))


if __name__ == "__main__":
    main()
